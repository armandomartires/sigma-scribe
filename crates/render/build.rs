//! Bakes the Lucide icons (assets/icons/lucide, ISC) into 8-bit alpha masks
//! at every size the UI scale needs (v1.1, plan decision 35): no SVG code
//! and no scaling at run time.

use std::fmt::Write as _;
use std::path::Path;

/// Icons used, by Lucide name.
const ICONS: &[&str] = &[
    "eye",
    "pencil",
    "search",
    "sticky-note",
    "list-todo",
    "table-of-contents",
    "share-2",
    "circle-help",
    "arrow-left",
    "folder",
    "x",
    // v1.5.3 handwriting panel.
    "arrow-left-right",
    "delete",
    "corner-down-left",
    "globe",
    "chevron-left",
    "chevron-right",
    "space",
    // v1.13 Kobo style keyboard.
    "arrow-big-up",
    // v1.13.1 Write panel keys.
    "undo-2",
    "redo-2",
    // v1.13.1 caret and page keys, Tab.
    "arrow-left-to-line",
    "arrow-right-to-line",
    "chevrons-up",
    "chevrons-down",
    "indent-increase",
    // v1.13.1 the Settings gear.
    "settings",
    // v1.16 the drawer button (the panel on the drawer's side).
    "panel-right",
    "panel-left",
];

/// A touch target is 44 brief units; the glyph is half of it.
const GLYPH_OF_TARGET: f32 = 0.5;
/// Forma short side 1440 / brief width 1264.
const FORMA: f32 = 1440.0 / 1264.0;
/// Lucide draws with 2 units; slightly thicker for e-ink.
const STROKE: &str = "2.25";

fn main() {
    let root = Path::new(env!("CARGO_MANIFEST_DIR")).join("../../assets/icons/lucide");
    println!("cargo:rerun-if-changed={}", root.display());
    // Every UI-scale step on the Forma, plus 1:1 steps for small panels.
    let mut sizes: Vec<u32> = [100u32, 125, 150, 175, 200]
        .iter()
        .map(|&p| (44.0 * FORMA * p as f32 / 100.0 * GLYPH_OF_TARGET).round() as u32)
        .collect();
    sizes.extend([16, 20]);
    sizes.sort_unstable();
    sizes.dedup();
    let mut out = String::from("// Generated by build.rs from Lucide (ISC).\n");
    out.push_str("/// The pixel sizes every icon is rendered at, smallest first.\n");
    let _ = writeln!(out, "pub static SIZES: &[u32] = &{sizes:?};");
    out.push_str("/// The icons as (Lucide name, size in pixels, row-major alpha mask).\n");
    out.push_str("pub static ICONS: &[(&str, u32, &[u8])] = &[\n");
    for name in ICONS {
        let path = root.join(format!("{name}.svg"));
        let svg = std::fs::read_to_string(&path).expect("lucide svg");
        let svg = svg.replace("stroke-width=\"2\"", &format!("stroke-width=\"{STROKE}\""));
        let tree =
            resvg::usvg::Tree::from_str(&svg, &resvg::usvg::Options::default()).expect("parse svg");
        for &sz in &sizes {
            let mut pm = resvg::tiny_skia::Pixmap::new(sz, sz).expect("pixmap");
            let k = sz as f32 / 24.0;
            resvg::render(
                &tree,
                resvg::tiny_skia::Transform::from_scale(k, k),
                &mut pm.as_mut(),
            );
            let alpha: Vec<u8> = pm.data().chunks(4).map(|p| p[3]).collect();
            let _ = writeln!(out, "    ({name:?}, {sz}, &{alpha:?}),");
        }
    }
    out.push_str("];\n");
    let dst = Path::new(&std::env::var("OUT_DIR").unwrap()).join("icons.rs");
    std::fs::write(dst, out).unwrap();
}
