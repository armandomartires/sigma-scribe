#!/bin/sh
# Build the GitHub wiki from docs/user/ into a checkout of the wiki repository.
#
#   git clone https://github.com/armandomartires/sigma-scribe.wiki.git /tmp/wiki
#   scripts/wiki-sync.sh [--force] /tmp/wiki
#   (cd /tmp/wiki && git status && git add -A && git commit && git push)
#
# docs/user/ is a help centre: README.md (the index, becomes Home) and
# NN-section/ folders, each with index.md (the section) and one .md file per
# article. One wiki page per .md file, named from the page's first "# " heading;
# the front block (--- title/summary/order ---) is dropped from the page body.
# Links between those pages become wiki links, links to other repository files
# absolute GitHub URLs, images raw.githubusercontent URLs. Also writes
# _Sidebar.md (grouped by section, in order) and _Footer.md. Home gains a line
# linking to the help centre on GitHub Pages. Every generated page starts with
# a marker comment; pages that carry it but no longer have a source are
# removed, other wiki pages are never touched. If a page to be written exists
# without the marker on its first line, the script refuses, before writing
# anything, unless --force is given. Nothing is committed or pushed.
set -eu

FORCE=0
if [ "${1:-}" = "--force" ]; then FORCE=1; shift; fi
[ $# -eq 1 ] && [ -d "$1" ] || { echo "usage: $0 [--force] <wiki-checkout-dir>" >&2; exit 2; }
ROOT=$(CDPATH= cd -- "$(dirname -- "$0")/.." && pwd)
exec python3 - "$ROOT" "$1" "$FORCE" <<'PY'
import os, re, sys

root, wiki, force = sys.argv[1], os.path.abspath(sys.argv[2]), sys.argv[3] == "1"
REPO = "https://github.com/armandomartires/sigma-scribe"
BLOB, TREE = REPO + "/blob/main/", REPO + "/tree/main/"
RAW = "https://raw.githubusercontent.com/armandomartires/sigma-scribe/main/"
MARK = "<!-- generated by scripts/wiki-sync.sh; edit docs/user in the repository -->"
udir = os.path.join(root, "docs", "user")
IMG = (".png", ".jpg", ".jpeg", ".gif", ".svg", ".webp")

FRONT = re.compile(r"\A---\n.*?\n---[ \t]*\n", re.S)

def read_page(path):
    with open(path, encoding="utf-8") as fh:
        text = fh.read().replace("\r\n", "\n")
    meta = {}
    m = FRONT.match(text)
    if m:
        for line in m.group(0).split("\n")[1:-2]:
            k, sep, v = line.partition(":")
            if sep:
                meta[k.strip()] = v.strip().strip("\"'")
        text = text[m.end():].lstrip("\n")
    h = re.search(r"^# +(.+?)\s*$", text, re.M)
    title = h.group(1) if h else os.path.splitext(os.path.basename(path))[0]
    try:
        order = int(meta.get("order", "999"))
    except ValueError:
        order = 999
    return {"path": path, "title": title, "order": order, "body": text}

# key = path under docs/user, with "/"
pages = {"README.md": read_page(os.path.join(udir, "README.md"))}
sections = []
for d in sorted(os.listdir(udir)):
    full = os.path.join(udir, d)
    if not (re.match(r"^\d+-", d) and os.path.isdir(full) and os.path.isfile(os.path.join(full, "index.md"))):
        continue
    sec = {"key": d + "/index.md", "articles": []}
    pages[sec["key"]] = read_page(os.path.join(full, "index.md"))
    arts = sorted((f for f in os.listdir(full) if f.endswith(".md") and f != "index.md"),
                  key=lambda f: (read_page(os.path.join(full, f))["order"], f))
    for f in arts:
        key = d + "/" + f
        pages[key] = read_page(os.path.join(full, f))
        sec["articles"].append(key)
    sections.append(sec)

names = {}
for key, pg in pages.items():
    name = "Home" if key == "README.md" else re.sub(r"[^\w.]+", "-", re.sub("['’]", "", pg["title"])).strip("-")
    if name in names.values():
        sys.exit("duplicate wiki page name %r (from %s)" % (name, key))
    names[key] = name
titles = {k: pg["title"] for k, pg in pages.items()}
bypath = {os.path.realpath(pg["path"]): k for k, pg in pages.items()}

warnings = []

def rel(path):
    return os.path.relpath(path, root).replace(os.sep, "/")

def rewrite_target(target, src):
    t = target.strip()
    if not t or t.startswith("#") or re.match(r"[a-zA-Z][a-zA-Z0-9+.-]*:", t):
        return target
    path, _, anchor = t.partition("#")
    full = os.path.normpath(os.path.join(os.path.dirname(src), path))
    r = rel(full)
    frag = "#" + anchor if anchor else ""
    if os.path.realpath(full) in bypath:
        return names[bypath[os.path.realpath(full)]] + frag
    if not os.path.exists(full):
        warnings.append("%s: link target does not exist: %s" % (rel(src), t))
    if r.lower().endswith(IMG):
        return RAW + r
    return (TREE if os.path.isdir(full) else BLOB) + r + frag

LINK = re.compile(r"(!?\[[^\]]*\]\()([^)\s]+)((?:\s+\"[^\"]*\")?\))")
REFDEF = re.compile(r"^(\s*\[[^\]]+\]:\s*)(\S+)", re.M)

def convert(text, src):
    out, fence = [], False
    for line in text.split("\n"):
        if re.match(r"\s*(```|~~~)", line):
            fence = not fence
            out.append(line)
            continue
        if fence:
            out.append(line)
            continue
        parts = re.split(r"(`[^`]*`)", line)  # leave code spans alone
        for i in range(0, len(parts), 2):
            p = LINK.sub(lambda m: m.group(1) + rewrite_target(m.group(2), src) + m.group(3), parts[i])
            parts[i] = REFDEF.sub(lambda m: m.group(1) + rewrite_target(m.group(2), src), p)
        out.append("".join(parts))
    return "\n".join(out)

HELP = "https://armandomartires.github.io/sigma-scribe/help/"
generated = {}
for key, pg in pages.items():
    body = convert(pg["body"], pg["path"])
    if key == "README.md":
        line = "Also available as a [help centre with search](%s)." % HELP
        m = re.search(r"^# .*$", body, re.M)
        body = body[:m.end()] + "\n\n" + line + body[m.end():] if m else line + "\n\n" + body
    generated[names[key] + ".md"] = MARK + "\n\n" + body

# Sidebar: Home, then each section (its index page, then its articles) in order.
side = ["**User guide**", "", "- [Home](Home)", "- [Help centre (with search)](%s)" % HELP]
for sec in sections:
    side += ["", "**[%s](%s)**" % (titles[sec["key"]], names[sec["key"]]), ""]
    for key in sec["articles"]:
        side.append("- [%s](%s)" % (titles[key], names[key]))
side += ["", "[Source](%s) · [Project page](https://armandomartires.github.io/sigma-scribe/)" % REPO]
generated["_Sidebar.md"] = MARK + "\n\n" + "\n".join(side) + "\n"
generated["_Footer.md"] = MARK + "\n\nGenerated from docs/user in the repository; edit there.\n"

if not force:
    clash = []
    for name in sorted(generated):
        p = os.path.join(wiki, name)
        if os.path.isfile(p):
            with open(p, encoding="utf-8") as fh:
                if fh.readline().strip() != MARK:
                    clash.append(name)
    if clash:
        sys.exit("refusing to overwrite wiki pages not written by this script (no marker on the first line): %s\nNothing was written. Use --force to overwrite them." % ", ".join(clash))

created, updated, same, removed = [], [], [], []
for name, content in sorted(generated.items()):
    p = os.path.join(wiki, name)
    old = None
    if os.path.exists(p):
        with open(p, encoding="utf-8") as fh:
            old = fh.read()
    if old == content:
        same.append(name)
        continue
    with open(p, "w", encoding="utf-8") as fh:
        fh.write(content)
    (created if old is None else updated).append(name)
for name in sorted(os.listdir(wiki)):
    p = os.path.join(wiki, name)
    if name.endswith(".md") and name not in generated and os.path.isfile(p):
        with open(p, encoding="utf-8") as fh:
            if fh.readline().strip() == MARK:
                os.remove(p)
                removed.append(name)

for label, lst in (("created", created), ("updated", updated), ("removed", removed), ("unchanged", same)):
    print("%s: %s" % (label, ", ".join(lst) if lst else "-"))
for w in warnings:
    print("warning: " + w, file=sys.stderr)
PY
