#!/usr/bin/env python3
"""Makes the Traditional (Taiwan phrases) seed files from the Simplified ones
with OpenCC (libopencc, s2twp), keeping the pinyin keys:
  assets/zh/seed-chars.txt -> seed-chars-hant.txt, seed-words.txt -> seed-words-hant.txt
Usage: tools/zh-hant.py   (needs libopencc.so.1.1 and /usr/share/opencc)"""
import ctypes, os, sys

lib = ctypes.CDLL("libopencc.so.1.1")
lib.opencc_open.restype = ctypes.c_void_p
lib.opencc_open.argtypes = [ctypes.c_char_p]
lib.opencc_convert_utf8.restype = ctypes.c_void_p
lib.opencc_convert_utf8.argtypes = [ctypes.c_void_p, ctypes.c_char_p, ctypes.c_size_t]
lib.opencc_convert_utf8_free.argtypes = [ctypes.c_void_p]
h = lib.opencc_open(b"/usr/share/opencc/s2twp.json")
if h in (None, 0) or ctypes.c_void_p(h).value == ctypes.c_void_p(-1).value:
    sys.exit("cannot open s2twp")

def s2t(s):
    b = s.encode()
    p = lib.opencc_convert_utf8(h, b, len(b))
    out = ctypes.string_at(p).decode()
    lib.opencc_convert_utf8_free(p)
    return out

root = os.path.join(os.path.dirname(__file__), "..", "assets", "zh")
for name in ("seed-chars", "seed-words"):
    out = []
    for line in open(os.path.join(root, name + ".txt"), encoding="utf-8"):
        line = line.rstrip("\n")
        if line.startswith("#") or not line.strip():
            out.append(line)
            continue
        if name == "seed-chars":
            key, cands = line.split(" ", 1)
            # keep each character distinct after conversion
            seen, res = set(), ""
            for c in cands:
                t = s2t(c)
                if t not in seen:
                    seen.add(t); res += t
            out.append(f"{key} {res}")
        else:
            key, _, word = line.rpartition(" ")
            out.append(f"{key} {s2t(word)}")
    head = "# Generated by tools/zh-hant.py from %s.txt with OpenCC s2twp (Apache-2.0); do not edit.\n" % name
    open(os.path.join(root, name + "-hant.txt"), "w", encoding="utf-8").write(head + "\n".join(out) + "\n")
    print(name, len(out))
